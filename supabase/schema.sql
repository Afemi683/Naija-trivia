-- 1. Create Profiles Table (extends auth.users)
CREATE TABLE IF NOT EXISTS public.profiles (
  id UUID REFERENCES auth.users(id) ON DELETE CASCADE PRIMARY KEY,
  username TEXT UNIQUE,
  full_name TEXT,
  avatar_url TEXT,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Enable RLS on profiles
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Public profiles are viewable by everyone." 
  ON public.profiles FOR SELECT USING (true);

CREATE POLICY "Users can insert their own profile." 
  ON public.profiles FOR INSERT WITH CHECK (auth.uid() = id);

CREATE POLICY "Users can update their own profile." 
  ON public.profiles FOR UPDATE USING (auth.uid() = id);

-- 2. Create Quiz Scores Table
CREATE TABLE IF NOT EXISTS public.quiz_scores (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  category TEXT NOT NULL,
  score INTEGER NOT NULL,
  total_questions INTEGER NOT NULL,
  streak INTEGER DEFAULT 0 NOT NULL,
  time_ms INTEGER DEFAULT 0 NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Enable RLS on quiz_scores
ALTER TABLE public.quiz_scores ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Scores are viewable by everyone on the leaderboard." 
  ON public.quiz_scores FOR SELECT USING (true);

CREATE POLICY "Users can insert their own quiz scores." 
  ON public.quiz_scores FOR INSERT WITH CHECK (
    auth.uid() IS NULL OR auth.uid() = user_id
  );

-- Indexes for fast leaderboard queries
CREATE INDEX IF NOT EXISTS idx_quiz_scores_category ON public.quiz_scores(category);
CREATE INDEX IF NOT EXISTS idx_quiz_scores_score ON public.quiz_scores(score DESC);
CREATE INDEX IF NOT EXISTS idx_quiz_scores_created ON public.quiz_scores(created_at DESC);

-- 3. Create Daily Challenges Table
CREATE TABLE IF NOT EXISTS public.daily_challenges (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  date TEXT NOT NULL,
  score INTEGER NOT NULL,
  total INTEGER NOT NULL,
  completed BOOLEAN DEFAULT true NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Enable RLS on daily_challenges
ALTER TABLE public.daily_challenges ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Daily challenges viewable by authenticated user." 
  ON public.daily_challenges FOR SELECT USING (
    auth.uid() IS NULL OR auth.uid() = user_id
  );

CREATE POLICY "Users can insert their daily challenges." 
  ON public.daily_challenges FOR INSERT WITH CHECK (
    auth.uid() IS NULL OR auth.uid() = user_id
  );

CREATE INDEX IF NOT EXISTS idx_daily_challenges_user_date 
  ON public.daily_challenges(user_id, date);

-- 4. Trigger: Automatically create profile on new user signup
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
BEGIN
  INSERT INTO public.profiles (id, full_name, username)
  VALUES (
    new.id,
    COALESCE(new.raw_user_meta_data->>'name', new.raw_user_meta_data->>'full_name', split_part(new.email, '@', 1)),
    split_part(new.email, '@', 1)
  );
  RETURN new;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();
